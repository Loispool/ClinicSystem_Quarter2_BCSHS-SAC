    /**
     * Refresh the diagnostics table from database
     */
    public void refreshDiagnosticsTable() {
        // Select all necessary fields from the diagnostics table
        String sql = "SELECT diagnostic_id, created_at, student_name, diagnostic_notes, student_lrn_fk FROM diagnostics ORDER BY created_at DESC";

        try (Connection conn = DatabaseConnector.getStudentConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            // Use DbUtils to convert ResultSet to TableModel
            DefaultTableModel model = (DefaultTableModel) DbUtils.resultSetToTableModel(rs);
            diagnosticsTable.setModel(model);

            // Set column headers
            if (model.getColumnCount() > 0) {
                diagnosticsTable.getColumnModel().getColumn(0).setHeaderValue("ID");
                diagnosticsTable.getColumnModel().getColumn(1).setHeaderValue("Visit Date");
                diagnosticsTable.getColumnModel().getColumn(2).setHeaderValue("Student Name");
                diagnosticsTable.getColumnModel().getColumn(3).setHeaderValue("Diagnostic Notes");
                diagnosticsTable.getColumnModel().getColumn(4).setHeaderValue("LRN");
            }

            System.out.println("✓ Diagnostics table refreshed: " + model.getRowCount() + " records");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Database Error: Cannot refresh table.\n" + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            logger.log(java.util.logging.Level.SEVERE, "SQL Error refreshing table", e);
        }
    }

    /**
     * Create initial diagnostic record for a newly registered student
     * This is called from RegistrationStudent after successful registration
     */
    public void createInitialDiagnosticRecord(String lrn, String firstName, String lastName) {
        String fullName = firstName + " " + lastName;
        String sql = "INSERT INTO diagnostics (student_lrn_fk, student_name, diagnostic_notes) VALUES (?, ?, ?)";

        try (Connection conn = DatabaseConnector.getStudentConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, lrn);
            pstmt.setString(2, fullName);
            pstmt.setString(3, "Student registered on " + new java.util.Date().toString() + ". Awaiting clinic visit.");

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                System.out.println("✓ Initial diagnostic record created for: " + fullName);
            }

            // Refresh the nurse's GUI immediately after a new record is created
            refreshDiagnosticsTable();

        } catch (SQLException e) {
            logger.log(java.util.logging.Level.SEVERE, "SQL Error creating initial record", e);
        }
    }

