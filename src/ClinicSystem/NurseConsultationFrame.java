    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // Save and Update button handler
        int selectedRow = diagnosticsTable.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this,
                    "Please select a student record from the table to update notes.",
                    "Selection Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Get the diagnostic_id from the selected row (first column)
        Object diagnosticIdObj = diagnosticsTable.getModel().getValueAt(selectedRow, 0);
        int diagnosticId = Integer.parseInt(diagnosticIdObj.toString());

        // Get the new notes from the text area
        String newNotes = jTextArea1.getText().trim();

        if (newNotes.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter diagnostic notes before saving.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Update the database
        String sql = "UPDATE diagnostics SET diagnostic_notes = ?, created_at = CURRENT_TIMESTAMP WHERE diagnostic_id = ?";

        try (Connection conn = DatabaseConnector.getStudentConnection();
             PreparedStatement pstmt = conn.prepareStatement(sql)) {

            pstmt.setString(1, newNotes);
            pstmt.setInt(2, diagnosticId);

            int rowsAffected = pstmt.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this,
                        "Diagnostic notes saved successfully!",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);

                // Clear the text area
                jTextArea1.setText("");

                // Refresh the table to show updated data
                refreshDiagnosticsTable();
            } else {
                JOptionPane.showMessageDialog(this,
                        "No records were updated. Please try again.",
                        "Update Failed",
                        JOptionPane.WARNING_MESSAGE);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Database Error: Could not save notes.\n" + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            logger.log(java.util.logging.Level.SEVERE, "SQL Error saving notes", e);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void diagnosticsTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_diagnosticsTableMouseClicked
        // When a row is clicked, load the current notes into the text area
        int selectedRow = diagnosticsTable.getSelectedRow();

        if (selectedRow != -1) {
            // Get the diagnostic notes from column 3 (adjust index if needed)
            Object notesObj = diagnosticsTable.getModel().getValueAt(selectedRow, 3);
            String currentNotes = (notesObj != null) ? notesObj.toString() : "";

            // Display in text area for editing
            jTextArea1.setText(currentNotes);
        }
    }//GEN-LAST:event_diagnosticsTableMouseClicked

